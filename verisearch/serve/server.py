"""Serve the trained policy: one question in, one grounded answer out.

PROJECT.md section 4 puts `serve/server.py` under Ayesha, and section 11 makes
P5 "vLLM serving + load benchmark", with the exit criterion "benchmark table
with real numbers at 3 concurrency levels". This module is the thing that
benchmark measures.

**A request is a whole episode, not one completion.** A VeriSearch answer is
several generate calls with retrieval in between: generate until `</search>`,
retrieve, inject `<info>`, generate again, until `<answer>`. Benchmarking vLLM's
`/v1/completions` directly would measure the part of the system vLLM already
benchmarks and none of what this project built - the turn count the policy
chose, the retrieval round trips, the injected context growing every turn. So
the unit here is a question, and the response is the answer the loop reached.

**No episode loop in this file.** The loop is `env/`, which is Dhrubo's. This
module accepts anything satisfying `PolicyRunner` and puts HTTP in front of it.
A second, hand-written copy of the loop here would mean benchmarking a system
that was never trained - the same two-code-paths failure `eval/harness.py`
refuses, for the same reason.

**Where concurrency actually comes from.** vLLM's continuous batching only pays
when several sequences are in flight against one engine at once. So a runner
behind this server must be safe to call from many threads, and must talk to a
vLLM *server* (`vllm serve`) rather than hold an offline `vllm.LLM`: that object
is not thread-safe, and the lock it would need makes "concurrency 32" measure
concurrency 1 with extra queueing. FastAPI runs a sync route in a worker thread
under anyio's default limiter of 40, so the shell itself does not cap section
9's highest level at 32.

**How this file is split** - the same way as `retrieval/service.py`, for the
same reason. `fastapi` is in the `[retrieval]` extra, so the PR pipeline never
installs it and `create_app` can never run in CI. Every decision about what the
server answers is therefore a pure function over the models above it, tested
directly, and `create_app` is wiring only.

Owner: Ayesha.
"""

from __future__ import annotations

import hashlib
from typing import TYPE_CHECKING, Protocol

from pydantic import BaseModel, ConfigDict, Field

from verisearch.retrieval.client import RetrievalError
from verisearch.types import Termination, Trajectory

if TYPE_CHECKING:
    from fastapi import FastAPI

_FROZEN = ConfigDict(frozen=True, extra="forbid")

# Bump when the wire format changes incompatibly. `/health` reports it and the
# benchmark client refuses a mismatch, so a stale server fails before any load
# is sent rather than producing a table of well-formed errors.
SERVE_PROTOCOL_VERSION = 1

# A memory amplifier otherwise, for the same reason `retrieval.service.MAX_K`
# exists: the question is prompt tokens on every turn of the episode. The
# longest HotpotQA question is a few hundred characters.
MAX_QUESTION_CHARS = 2000

# Long enough for a dataset id with a prefix, short enough that it cannot carry
# a payload. Bounded because it is echoed into every response and log line.
MAX_QUESTION_ID_CHARS = 128


class ServeError(Exception):
    """A request that cannot be served, with the status code it maps to.

    Same shape as `retrieval.service.ServiceError`: the pure handler decides the
    code, so the one judgement call per failure lives where it is tested.
    """

    def __init__(self, message: str, *, status_code: int) -> None:
        super().__init__(message)
        self.status_code = status_code


class PolicyRunner(Protocol):
    """Runs one episode of the policy on one question.

    Deliberately the whole of this server's dependency on generation. The id is
    passed in rather than generated by the runner so the server can check that
    the trajectory it gets back belongs to the request it is answering.

    Must be safe to call concurrently - see the module docstring.
    """

    def run(self, question_id: str, question: str) -> Trajectory: ...


class AnswerRequest(BaseModel):
    """One question. `question_id` is optional; the server derives one if absent."""

    model_config = _FROZEN

    question: str = Field(min_length=1, max_length=MAX_QUESTION_CHARS)
    question_id: str | None = Field(default=None, min_length=1, max_length=MAX_QUESTION_ID_CHARS)


class Source(BaseModel):
    """One passage the answer was written with in context."""

    model_config = _FROZEN

    doc_id: str
    title: str


class AnswerResponse(BaseModel):
    """What the episode produced.

    Echoes `question_id` back. Not redundant, for the reason
    `retrieval.service.SearchResponse` echoes its query: a response matched to
    the wrong request is otherwise invisible, because it is a perfectly
    well-formed answer to some other question.

    `answer` is None when the episode ended without one. That is a 200, not an
    error - the server worked, the policy gave up - and `termination` says why.
    The benchmark counts it separately, because a policy that gives up early is
    fast, and a latency table that cannot see that flatters it.
    """

    model_config = _FROZEN

    question_id: str
    answer: str | None
    termination: Termination
    search_queries: tuple[str, ...]
    sources: tuple[Source, ...]


class ServeHealth(BaseModel):
    """What this server is serving, for the benchmark to record rather than be told.

    `hardware` is reported by the server because the server is what is being
    measured. The benchmark client may run on a different machine, and a hardware
    line typed by whoever ran the script is how a table ends up describing the
    laptop it was launched from.
    """

    model_config = _FROZEN

    ok: bool
    protocol_version: int
    policy: str = Field(min_length=1)
    # The LoRA checkpoint being served. None means the base model, which is a
    # legitimate thing to benchmark and must not be mistaken for a trained one.
    adapter: str | None
    hardware: str = Field(min_length=1)
    config_fingerprint: str = Field(min_length=1)


def question_id_for(question: str) -> str:
    """A stable id for a request that did not bring one.

    Derived from the text rather than random, so the same question gets the same
    id in two logs. It is not a uniqueness guarantee - two callers asking the
    same thing get the same id - which is why `handle_answer` checks the
    question text as well as the id.
    """
    digest = hashlib.sha256(question.encode("utf-8")).hexdigest()[:12]
    return f"serve-{digest}"


def handle_answer(runner: PolicyRunner, request: AnswerRequest) -> AnswerResponse:
    """Answer one question. All of the server's behaviour.

    **An unreachable dependency is a 503, never an answer.** If retrieval is
    down mid-episode, an answer written without the passages it asked for is
    exactly the unsupported claim this project exists to measure - and it would
    arrive with a 200 and a plausible sentence in it. The same holds for a vLLM
    server that cannot be reached. Both map to 503 so a client retries later
    rather than trusting the response.

    Anything else a runner raises is a bug and propagates as one.
    """
    if not request.question.strip():
        raise ServeError("question is blank", status_code=400)

    question_id = request.question_id or question_id_for(request.question)
    try:
        trajectory = runner.run(question_id, request.question)
    except RetrievalError as exc:
        # Named explicitly: `RetrievalError` is a `ValueError`, not an `OSError`,
        # so the clause below would miss it, and this is the case that matters.
        raise ServeError(f"retrieval failed mid-episode: {exc}", status_code=503) from exc
    except OSError as exc:
        raise ServeError(f"a dependency is unreachable: {exc}", status_code=503) from exc

    if trajectory.question_id != question_id or trajectory.question != request.question:
        # Under concurrency this is one caller receiving another caller's
        # answer. Every field is well-formed, so nothing downstream would notice.
        raise ServeError(
            f"runner returned the episode for {trajectory.question_id!r} while answering "
            f"{question_id!r}; refusing to hand one caller another caller's answer",
            status_code=500,
        )

    return AnswerResponse(
        question_id=question_id,
        answer=trajectory.answer,
        termination=trajectory.termination,
        search_queries=trajectory.search_queries,
        sources=_sources(trajectory),
    )


def _sources(trajectory: Trajectory) -> tuple[Source, ...]:
    """Every passage the policy saw, first appearance first, each once.

    The same passage retrieved by two searches was in context once as far as a
    reader of the answer is concerned, so it is listed once.
    """
    seen: set[str] = set()
    sources: list[Source] = []
    for passage in trajectory.retrieved_passages:
        if passage.doc_id not in seen:
            seen.add(passage.doc_id)
            sources.append(Source(doc_id=passage.doc_id, title=passage.title))
    return tuple(sources)


def handle_health(
    *,
    policy: str,
    adapter: str | None,
    hardware: str,
    config_fingerprint: str,
) -> ServeHealth:
    """Report what this server is serving."""
    return ServeHealth(
        ok=True,
        protocol_version=SERVE_PROTOCOL_VERSION,
        policy=policy,
        adapter=adapter,
        hardware=hardware,
        config_fingerprint=config_fingerprint,
    )


def create_app(  # pragma: no cover - fastapi is in the [retrieval] extra
    runner: PolicyRunner,
    health: ServeHealth,
) -> FastAPI:
    """Wire the handlers above into a FastAPI app.

    **Unverified.** `fastapi` is not installed in CI or on this machine, so
    nothing in this function has run. It holds no decisions for that reason:
    one route per handler, plus one exception translation. If a bug is ever
    traced here, the fix is to move the logic into a handler, not to test the
    route.

    The routes are sync `def` on purpose. FastAPI runs those in a thread pool,
    which is where the concurrency comes from; an `async def` route calling a
    blocking runner would serialise every request on the event loop.
    """
    try:
        from fastapi import FastAPI, HTTPException
    except ImportError as exc:
        raise ServeError(
            "the policy server needs fastapi: uv pip install -e '.[retrieval]'",
            status_code=500,
        ) from exc

    def get_health() -> ServeHealth:
        return health

    def answer(request: AnswerRequest) -> AnswerResponse:
        try:
            return handle_answer(runner, request)
        except ServeError as exc:
            raise HTTPException(status_code=exc.status_code, detail=str(exc)) from exc

    app = FastAPI(title="VeriSearch policy", version=str(SERVE_PROTOCOL_VERSION))
    # `add_api_route` rather than decorators - see `retrieval/service.py` for why
    # the decorators fail `mypy --strict` under `ignore_missing_imports`.
    app.add_api_route("/health", get_health, methods=["GET"], response_model=ServeHealth)
    app.add_api_route("/answer", answer, methods=["POST"], response_model=AnswerResponse)
    return app
